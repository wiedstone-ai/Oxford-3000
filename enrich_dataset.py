# Function to clean SQL translation
def clean_sql_trans(raw):
    if not raw:
        return ''
    s = re.sub(r'\b(kb|kkt|kki|ks|kk|ksp|kd|kg|Inf|j|lih)\.\s*', '', raw)
    s = re.sub(r'\s+', ' ', s)
    parts = re.split(r'\s*\d+\s*', s)
    items = []
    for p in parts:
        p = p.strip(' ,;.-')
        sub_p = re.split(r'\.\s+[A-Z]', p)[0].strip(' ,;.-')
        # remove text inside parentheses if purely grammar/inflection
        sub_p = re.sub(r'\(.*?\)', '', sub_p).strip(' ,;.-')
        if sub_p and len(sub_p) > 1 and not sub_p.startswith('--'):
            # take first 2 terms
            sub_terms = [t.strip() for t in sub_p.split(',') if t.strip()]
            items.extend(sub_terms[:2])
    # unique preserve order
    seen = set()
    uniq = []
    for it in items:
        it_clean = it.strip()
        if it_clean and it_clean.lower() not in seen and len(it_clean) > 1:
            seen.add(it_clean.lower())
            uniq.append(it_clean)
    res = ', '.join(uniq[:3])
    return res

# Function to get Indonesian translation
def get_arti(word, base_clean):
    w_lower = word.lower()
    b_lower = base_clean.lower()
    
    if b_lower in custom_id_trans:
        return custom_id_trans[b_lower]
    if w_lower in custom_id_trans:
        return custom_id_trans[w_lower]
    
    # Try database
    c.execute("SELECT trans FROM data_en_id WHERE word = ? COLLATE NOCASE", (b_lower,))
    row = c.fetchone()
    if row:
        cleaned = clean_sql_trans(row[0])
        if cleaned:
            return cleaned
            
    # Try stemmed or related forms
    if b_lower.endswith('ly'):
        stem = b_lower[:-2]
        c.execute("SELECT trans FROM data_en_id WHERE word = ? COLLATE NOCASE", (stem,))
        row = c.fetchone()
        if row:
            cl = clean_sql_trans(row[0])
            if cl:
                return f"secara {cl}, dengan {cl}"
    if b_lower.endswith('ing'):
        stem = b_lower[:-3]
        c.execute("SELECT trans FROM data_en_id WHERE word = ? COLLATE NOCASE", (stem,))
        row = c.fetchone()
        if row:
            cl = clean_sql_trans(row[0])
            if cl:
                return cl
    if b_lower.endswith('ed'):
        stem = b_lower[:-2]
        c.execute("SELECT trans FROM data_en_id WHERE word = ? COLLATE NOCASE", (stem,))
        row = c.fetchone()
        if row:
            cl = clean_sql_trans(row[0])
            if cl:
                return f"ter{cl}, di{cl}"

    return b_lower.capitalize()

